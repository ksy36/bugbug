"""Snapshot a broken site into a static, anonymized copy for evals.

Python fetches the bug and its attached Puppeteer reproduction script from
Bugzilla and runs the script in Firefox and Chrome. Only when it still shows
the difference (Firefox exits 1, Chrome exits 0) does the agent run. The agent
only gets the URL: it copies the site into static files with synthetic content
and checks in Firefox that the copy matches the original, which carries over
the breakage without the agent having to know what it is.
"""

import base64
import json
import logging
import os
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated, Any, Literal

import requests
from autowebcompat_tools.task import RunTracker, Task, TaskConfig
from pydantic import BaseModel, Field

from .config import DEVTOOLS_TOOLS
from .mcp_servers import WORK_DIR, build_firefox_devtools_server

HERE = Path(__file__).resolve().parent

logger = logging.getLogger("autowebcompat-snapshot")

SCRIPT_DESCRIPTION = "Reproduction script generated by autowebcompat bot"


@dataclass
class Bug:
    bug_id: int
    summary: str
    url: str
    script: bytes | None


def fetch_bug(api_url: str, bug_id: int) -> Bug:
    """Read a public bug and its reproduction script."""

    def get(path: str, **params: str) -> Any:
        response = requests.get(f"{api_url.rstrip('/')}{path}", params, timeout=60)
        response.raise_for_status()
        return response.json()

    bug = get(f"/bug/{bug_id}", include_fields="summary,url")["bugs"][0]
    attachments = get(f"/bug/{bug_id}/attachment")["bugs"][str(bug_id)]

    scripts = [
        a
        for a in attachments
        if not a["is_obsolete"] and a["file_name"].endswith((".mjs", ".js"))
    ]
    # Prefer the bot's script; the newest one wins.
    scripts.sort(key=lambda a: (a["description"] == SCRIPT_DESCRIPTION, a["id"]))

    return Bug(
        bug_id=bug_id,
        summary=bug["summary"],
        url=bug["url"],
        script=base64.b64decode(scripts[-1]["data"]) if scripts else None,
    )


def run_script(
    script_path: Path, browser: str, browser_path: Path, headless: bool
) -> int | None:
    """Run the reproduction script in one browser; return its exit code.

    Returns ``None`` if the script timed out, i.e. gave no verdict.
    """
    env = {**os.environ, "BROWSER": browser, "BROWSER_BIN": str(browser_path)}
    if headless:
        env["HEADLESS"] = "1"
    try:
        proc = subprocess.run(
            ["node", str(script_path)],
            env=env,
            capture_output=True,
            text=True,
            timeout=5 * 60,
        )
    except subprocess.TimeoutExpired:
        logger.warning("%s: script timed out in %s", script_path.name, browser)
        return None
    logger.info(
        "%s exited %s in %s\nstdout:\n%s\nstderr:\n%s",
        script_path.name,
        proc.returncode,
        browser,
        proc.stdout,
        proc.stderr,
    )
    return proc.returncode


class SnapshotResult(BaseModel):
    status: Annotated[
        Literal["ok"] | Literal["snapshot_failed"],
        Field(
            description=(
                "`ok` if the local copy looks and behaves like the original "
                "in Firefox, otherwise `snapshot_failed`."
            )
        ),
    ]
    failure_reason: Annotated[
        str | None,
        Field(description="Why the snapshot failed, in one sentence. null if ok."),
    ]
    entry_path: Annotated[
        str | None,
        Field(
            description=(
                "Path of the page to open, relative to the site directory "
                "(e.g. `index.html`). null if the snapshot failed."
            )
        ),
    ]


class Snapshot(Task[SnapshotResult]):
    name = "snapshot"
    result_cls = SnapshotResult
    result_server_name = "snapshot"

    def __init__(
        self,
        task_config: TaskConfig,
        run_tracker: RunTracker,
        firefox_path: Path,
        url: str,
        site_dir: Path,
    ):
        super().__init__(task_config, run_tracker)
        self.allowed_tools += ["Write", "Edit"]
        self.url = url
        self.site_dir = site_dir
        self.add_mcp_server(
            "firefox-devtools",
            build_firefox_devtools_server(firefox_path, headless=task_config.headless),
            DEVTOOLS_TOOLS,
        )

    def subject(self) -> Any:
        return self.url

    def system_prompt(self) -> str:
        return (
            (HERE / "prompts" / "system.md")
            .read_text()
            .format(site_dir=self.site_dir, work_dir=WORK_DIR)
        )

    def user_prompt(self) -> str:
        return f"Snapshot {self.url}"


async def snapshot_bug(
    config: TaskConfig,
    bugzilla_api_url: str,
    bug_id: int,
    firefox_path: Path,
    chrome_path: Path,
    bug_dir: Path,
) -> dict[str, Any]:
    """Snapshot one bug into ``bug_dir``; return its entry for the index."""
    bug = fetch_bug(bugzilla_api_url, bug_id)
    if bug.script is None:
        return {"status": "no_script", "url": bug.url}

    # The script must live next to node_modules for `import puppeteer-core`
    # to resolve (ESM ignores NODE_PATH).
    script_path = WORK_DIR / f"reproduction-{bug_id}.mjs"
    script_path.write_bytes(bug.script)
    firefox_exit = run_script(script_path, "firefox", firefox_path, config.headless)
    chrome_exit = run_script(script_path, "chrome", chrome_path, config.headless)
    if (firefox_exit, chrome_exit) != (1, 0):
        return {
            "status": "not_reproduced",
            "url": bug.url,
            "reason": f"script exit codes: firefox={firefox_exit}, chrome={chrome_exit}",
        }

    site_dir = bug_dir / "site"
    site_dir.mkdir(parents=True, exist_ok=True)
    tracker = RunTracker()
    task = Snapshot(config, tracker, firefox_path, bug.url, site_dir)
    result = await task.run()

    if result.status == "ok" and not (
        result.entry_path and (site_dir / result.entry_path).is_file()
    ):
        result.status = "snapshot_failed"
        result.failure_reason = f"entry page {result.entry_path!r} does not exist"

    manifest = {
        "bug_id": bug_id,
        "bug_summary": bug.summary,
        "original_url": bug.url,
        **result.model_dump(),
    }
    (bug_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return {
        "status": result.status,
        "url": bug.url,
        "reason": result.failure_reason,
        "cost_usd": tracker.total_cost_usd,
    }
